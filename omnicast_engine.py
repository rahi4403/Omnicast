def normalize_language_name(lang):
    """
    Normalizes any language string or dialect alias (e.g. 'oriya' -> 'Odia', 'telegulu' -> 'Telugu')
    to standard 15-language key.
    """
    if not lang:
        return "Hindi"
    clean = str(lang).strip().lower()
    if clean in LANGUAGE_ALIASES:
        return LANGUAGE_ALIASES[clean]
    for key in LANGUAGES_CONFIG.keys():
        if key.lower() == clean:
            return key
    return "Hindi"

