def is_predominantly_english(text):
    if not text:
        return True
    clean_lower = str(text).lower().strip()
    if any(b["id"] in clean_lower for b in DEFAULT_BALL_FEED) or re.match(r'^ball[-\s]?\d+', clean_lower):
        return True
    if any(b["raw_text"].lower().strip() == clean_lower for b in DEFAULT_BALL_FEED):
        return True
    ascii_letters = sum(1 for c in text if c.isascii() and c.isalpha())
    indic_letters = sum(1 for c in text if not c.isascii())
    return ascii_letters > 0 and ascii_letters >= indic_letters

def generate_voice_mail(text_to_speak, selected_lang="Bengali", recipient_name="All Fans", celebration_tag="", audience_mode="rookie", cultural_tone="standard"):
    """
    Generating voice mail audio with gTTS and saving to static/audio/
    Ensures:
    1. Cleaned text free of unwanted slang (100% pure cricket)
    2. 100% Cricket commentary matching target language
    3. Proper phonetic Indic TTS engine (tts_engine)
    """
    selected_lang = normalize_language_name(selected_lang)
    lang_info = LANGUAGES_CONFIG[selected_lang]
    tts_code = lang_info.get("tts_engine", lang_info.get("gtts", "en"))

    # Clean input
    if text_to_speak:
        text_to_speak = clean_cricket_commentary_text(text_to_speak)

    # 1. If text is empty or raw English dataset commentary, adapt it to selected_lang with requested cultural tone
    is_raw_feed_match = any(b["raw_text"].lower().strip() == str(text_to_speak).lower().strip() for b in DEFAULT_BALL_FEED)
    if not text_to_speak or not text_to_speak.strip() or (is_raw_feed_match and selected_lang != "English"):
        source_text = text_to_speak.strip() if text_to_speak and text_to_speak.strip() else DEFAULT_BALL_FEED[0]["raw_text"]
        text_to_speak = adapt_commentary_multilingual(
            raw_text=source_text,
            audience_mode=audience_mode,
            target_lang=selected_lang,
            cultural_tone=cultural_tone
        )

    # 2. Add localized cricket recipient greeting if specified
    full_speech_script = text_to_speak
    if recipient_name and recipient_name.strip() and recipient_name.strip() != "All Fans":
        greeting_template = LOCALIZED_GREETINGS.get(selected_lang, LOCALIZED_GREETINGS["English"])
        prefix = greeting_template.format(recipient=recipient_name.strip())
        full_speech_script = prefix + full_speech_script

    # 3. Add cricket celebration outro tag if specified
    if celebration_tag and celebration_tag.strip():
        outro_text = ""
        tag_lower = celebration_tag.lower()
        if "winning" in tag_lower or "match" in tag_lower:
            outro_text = LOCALIZED_CELEBRATIONS["winning"].get(selected_lang, celebration_tag)
        elif "sensational" in tag_lower or "performance" in tag_lower or "ecstasy" in tag_lower:
            outro_text = LOCALIZED_CELEBRATIONS["sensational"].get(selected_lang, celebration_tag)
        elif "changer" in tag_lower or "timber" in tag_lower or "delivery" in tag_lower or "wicket" in tag_lower:
            outro_text = LOCALIZED_CELEBRATIONS["game_changer"].get(selected_lang, celebration_tag)
        else:
            outro_text = celebration_tag

        full_speech_script = f"{full_speech_script} {outro_text}"

    # Clean speech script once more to ensure complete absence of unwanted phrases
    full_speech_script = clean_cricket_commentary_text(full_speech_script)
    if not full_speech_script or not full_speech_script.strip():
        full_speech_script = adapt_commentary_multilingual(
            raw_text=DEFAULT_BALL_FEED[0]["raw_text"],
            audience_mode=audience_mode,
            target_lang=selected_lang,
            cultural_tone=cultural_tone
        )

    # 4. Generate unique filename hash
    text_hash = hashlib.md5(f"{selected_lang}_{tts_code}_{full_speech_script}".encode('utf-8')).hexdigest()[:10]
    filename = f"omnicast_{selected_lang.lower()}_{text_hash}.mp3"
    filepath = os.path.join(AUDIO_DIR, filename)

    audio_bytes = None
    if os.path.exists(filepath):
        try:
            with open(filepath, "rb") as f:
                audio_bytes = f.read()
        except Exception:
            audio_bytes = None

    if not audio_bytes:
        fp = io.BytesIO()
        try:
            tts = gTTS(text=full_speech_script, lang=tts_code)
            tts.write_to_fp(fp)
            fp.seek(0)
            audio_bytes = fp.read()
        except Exception as e:
            fallback_lang = "hi" if not full_speech_script.isascii() else "en"
            print(f"TTS fallback to {fallback_lang}: {e}")
            try:
                fp = io.BytesIO()
                tts = gTTS(text=full_speech_script, lang=fallback_lang)
                tts.write_to_fp(fp)
                fp.seek(0)
                audio_bytes = fp.read()
            except Exception as e2:
                print(f"Second fallback: {e2}")
                fp = io.BytesIO()
                tts = gTTS(text="OmniCast Cricket Commentary Audio", lang="en")
                tts.write_to_fp(fp)
                fp.seek(0)
                audio_bytes = fp.read()

        # Best-effort disk save for environments with write permission (e.g. local dev)
        if audio_bytes:
            try:
                with open(filepath, "wb") as f:
                    f.write(audio_bytes)
            except OSError:
                pass

    file_size_kb = round(len(audio_bytes) / 1024, 1) if audio_bytes else 0
    audio_b64 = base64.b64encode(audio_bytes).decode('ascii') if audio_bytes else ""
    audio_data_url = f"data:audio/mp3;base64,{audio_b64}" if audio_b64 else f"/static/audio/{filename}"

    return {
        "success": True,
        "language": selected_lang,
        "tts_code": lang_info["gtts"],
        "engine_tts": tts_code,
        "filename": filename,
        "audio_url": audio_data_url,
        "static_url": f"/static/audio/{filename}",
        "script": full_speech_script,
        "body_text": text_to_speak,
        "file_size_kb": file_size_kb,
        "recipient": recipient_name
    }
