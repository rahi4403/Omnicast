# 9. Commentary Multilingual Adaptation Logic
# -------------------------------------------------------------
def adapt_commentary_multilingual(raw_text, audience_mode="rookie", target_lang="Hindi", cultural_tone="standard"):
    target_lang = normalize_language_name(target_lang)
    audience_mode = audience_mode if audience_mode in ["rookie", "expert", "casual"] else "rookie"
    mode_key = "expert" if audience_mode == "expert" else "rookie"

    matched_key = find_matching_ball_key(raw_text)

    if matched_key and matched_key in KNOWLEDGE_BASE:
        ball_dict = KNOWLEDGE_BASE[matched_key][mode_key]
        base_adaptation = ball_dict.get(target_lang, ball_dict["Hindi"])
    else:
        category = detect_action_category(raw_text)
        action_dict = DYNAMIC_ACTION_MAP.get(category, DYNAMIC_ACTION_MAP["defense"])[mode_key]
        base_adaptation = action_dict.get(target_lang, action_dict["Hindi"])

    # Clean any unwanted phrases
    base_adaptation = clean_cricket_commentary_text(base_adaptation)

    # Layer cultural dialect tone if requested (all 100% pure cricket phrasing)
    if cultural_tone in DIALECT_TEMPLATES and cultural_tone != "standard":
        preset = DIALECT_TEMPLATES[cultural_tone]
        prefix = preset.get("prefix", "")
        suffix = preset.get("suffix", "")
        adapted_output = f"{prefix}{base_adaptation}{suffix}"
    else:
        adapted_output = base_adaptation

    return clean_cricket_commentary_text(adapted_output)

