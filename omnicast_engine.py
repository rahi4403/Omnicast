def detect_action_category(text):
    text_lower = str(text).lower()
    if any(k in text_lower for k in ["six", "maximum", "bouncer", "pulled", "top tier", "105 meters", "98 meters"]):
        return "maximum"
    elif any(k in text_lower for k in ["four", "boundary", "flicked", "whip", "mid-on", "mid-off", "cover", "crunched"]):
        return "boundary"
    elif any(k in text_lower for k in ["wicket", "bowled", "yorker", "shattered", "out", "caught", "lbw", "timber"]):
        return "wicket"
    else:
        return "defense"

def find_matching_ball_key(raw_text):
    if not raw_text:
        return "ball-1"
    clean_lower = str(raw_text).lower().strip()
    for ball in DEFAULT_BALL_FEED:
        if ball["id"] in clean_lower or ball["raw_text"].lower().strip() == clean_lower:
            return ball["id"]
        # Match keywords
        if "left alone" in clean_lower or "short of a length" in clean_lower:
            return "ball-1"
        elif "wristy whip" in clean_lower or ("four" in clean_lower and "mid-on" in clean_lower):
            return "ball-2"
        elif "slower bouncer" in clean_lower or "98 meters" in clean_lower:
            return "ball-3"
        elif "base of leg stump" in clean_lower or "timber shattered" in clean_lower or "unplayable yorker" in clean_lower:
            return "ball-4"
        elif "behind point" in clean_lower or "pinch two runs" in clean_lower:
            return "ball-5"
        elif "105 meters" in clean_lower or "like a golfer" in clean_lower:
            return "ball-6"
        elif "crunched through extra cover" in clean_lower or "pierces the sweeper" in clean_lower:
            return "ball-7"
        elif "searing 148 km/h" in clean_lower or "rattles off stump" in clean_lower:
            return "ball-8"
    return None

