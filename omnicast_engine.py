# 10. Generate Multilingual Matrix (All 15 Languages)
# -------------------------------------------------------------
def generate_multilingual_matrix(raw_text, audience_mode="rookie", cultural_tone="standard"):
    results = []
    for lang_key, info in LANGUAGES_CONFIG.items():
        translated = adapt_commentary_multilingual(
            raw_text=raw_text,
            audience_mode=audience_mode,
            target_lang=lang_key,
            cultural_tone=cultural_tone
        )
        results.append({
            "Language": lang_key,
            "gTTS Code": info["gtts"],
            "Native Name": info["native"],
            "Region": info["region"],
            "Flag": info["flag"],
            "Adapted Commentary": translated,
            "CharCount": len(translated)
        })
    return results

